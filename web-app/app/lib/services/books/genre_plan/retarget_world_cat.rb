# frozen_string_literal: true

module Services
  module Books
    module GenrePlan
      # `categories:genres:retarget_worldcat` (spec §7): rewrites the WorldCat
      # genre map's targets from the plan, in development, for the same PR as
      # the plan. Reads only the plan and the map file.
      class RetargetWorldCat
        Result = Struct.new(:success?, :data, :errors, keyword_init: true)
        KEPT_KEYS = %w[language uses books].freeze
        HEADER = "# WorldCat genre terms -> our curated genres and audiences. Generated by `bin/rails worldcat:map`\n" \
                 "# on 2026-10-12, edited by hand, and retargeted by `categories:genres:retarget_worldcat`.\n"
        CHILDRENS = "Children's"

        def self.call(plan:, path: ::Books::WorldCat::GenreMap::DEFAULT_PATH)
          new(plan, Pathname(path)).call
        end

        def initialize(plan, path)
          @plan = plan
          @path = path
          @by_name = plan.decisions.values.index_by { |d| d["name"] }
        end

        def call
          data = YAML.safe_load_file(@path)
          errors = []
          retargeted = 0
          terms = data["terms"].to_h do |term, entry|
            next [term, entry] unless %w[genre audience].include?(entry["verdict"])

            target = entry["genre"] || entry["audience"]
            decision = @by_name[target]
            if decision.nil?
              errors << "#{term.inspect} targets #{target.inspect}, which the plan does not know" unless list_name?(target)
              next [term, entry]
            end

            fresh = rewrite(term, decision, errors)
            next [term, entry] if fresh.nil?

            retargeted += 1 unless fresh == entry.except(*KEPT_KEYS)
            [term, fresh.merge(entry.slice(*KEPT_KEYS))]
          end
          return Result.new(success?: false, data: nil, errors: errors) if errors.any?

          out = {"version" => data["version"], "genres" => @plan.genre_names, "audiences" => @plan.audience_names, "terms" => terms}
          @path.write(HEADER + out.to_yaml)
          Result.new(success?: true, data: {retargeted: retargeted}, errors: [])
        end

        private

        def list_name?(name) = @plan.genre_names.include?(name) || @plan.audience_names.include?(name)

        def rewrite(term, decision, errors)
          return verdict(term, [decision["worldcat"]]) if decision["worldcat"]

          case decision["action"]
          when "keep" then verdict(term, [decision["name"]])
          when "rename" then verdict(term, [decision["to"]])
          when "merge" then verdict(term, [decision["into"]])
          when "audience" then verdict(term, [decision["as"]])
          when "subject" then {"verdict" => "subject", "subject" => decision["as"] || decision["name"]}
          when "location", "delete" then dropped
          when "split" then split_verdict(term, decision, errors)
          end
        end

        def split_verdict(term, decision, errors)
          answers = decision["worldcat_terms"] || {}
          unless answers.key?(term)
            errors << "#{term.inspect} targets the split genre #{decision["name"].inspect} but is not in its worldcat_terms"
            return nil
          end
          names = Array(answers[term])
          # An empty answer: the term supports none of the halves.
          names.empty? ? dropped : verdict(term, names)
        end

        def dropped = {"verdict" => "drop", "reason" => "not_a_genre"}

        # names: primary first; the rest go in `also`. GenreMap honours `weak`
        # only on an audience primary, so a juvenile term that names Children's
        # puts it first, otherwise it would count as strong evidence in `also`.
        def verdict(term, names)
          weak = juvenile?(term) && names.include?(CHILDRENS)
          names = [CHILDRENS] + (names - [CHILDRENS]) if weak
          primary = names.first
          out = if @plan.audience_names.include?(primary)
            {"verdict" => "audience", "audience" => primary}
          else
            {"verdict" => "genre", "genre" => primary}
          end
          out["weak"] = true if weak
          out["also"] = names.drop(1) if names.size > 1
          out
        end

        # WorldCat's "Juvenile" spans ages 0-15 (spec §7).
        def juvenile?(term) = term.match?(/\bjuvenile\b/i)
      end
    end
  end
end
